import { mkdir, readFile, writeFile } from "node:fs/promises"
import "mjml"
import core from "mjml-core"
import preset from "mjml-preset-core"

const sourcePath = "contract/letterpress-v1.json"
const generatedPath = "generated/letterpress-v1.json"
const browserPath = "npm/language/src/generated/contract.ts"
const source = JSON.parse(await readFile(sourcePath, "utf8"))

const componentMetadata = Object.fromEntries(
  Object.entries(core.components)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, component]) => [
      name,
      {
        attributes: sortObject(component.allowedAttributes ?? {}),
        defaults: sortObject(component.defaultAttributes ?? {}),
        ending_tag: component.endingTag === true,
      },
    ]),
)

const officialAttributes = sortObject(
  Object.assign({}, ...Object.values(componentMetadata).map((component) => component.attributes)),
)

const allElementMetadata = {
  ...componentMetadata,
  mjml: {
    attributes: { dir: "enum(ltr,rtl,auto)", lang: "string", owa: "enum(mobile,desktop)" },
    defaults: {},
    ending_tag: true,
  },
  "mj-all": {
    attributes: officialAttributes,
    defaults: {},
    ending_tag: false,
  },
  "mj-class": {
    attributes: sortObject({ ...officialAttributes, name: "string" }),
    defaults: {},
    ending_tag: true,
  },
  "mj-selector": {
    attributes: { path: "string" },
    defaults: {},
    ending_tag: true,
  },
  "mj-html-attribute": {
    attributes: { name: "string" },
    defaults: {},
    ending_tag: true,
  },
}

const enabledElements = new Set(source.profiles["email/mjml-liquid@1"].elements)
const elementMetadata = sortObject(
  Object.fromEntries(
    Object.entries(allElementMetadata).filter(([name]) => enabledElements.has(name)),
  ),
)

const nesting = Object.fromEntries(
  Object.entries(preset.dependencies)
    .sort(([left], [right]) => left.localeCompare(right))
    .filter(([parent]) => enabledElements.has(parent))
    .map(([parent, children]) => [
      parent,
      children
        .map((child) => (child instanceof RegExp ? "*" : child))
        .filter((child) => child === "*" || enabledElements.has(child))
        .sort(),
    ]),
)

const generated = {
  ...source,
  generated_from: {
    mjml: "5.4.0",
    source: sourcePath,
  },
  profiles: {
    ...source.profiles,
    "email/mjml-liquid@1": {
      ...source.profiles["email/mjml-liquid@1"],
      element_metadata: elementMetadata,
      nesting,
    },
  },
}

const json = `${JSON.stringify(generated, null, 2)}\n`
await mkdir("generated", { recursive: true })
await mkdir("npm/language/src/generated", { recursive: true })
await writeFile(generatedPath, json)
await writeFile(
  browserPath,
  `// Generated by scripts/generate-contract.mjs. Do not edit.\nexport const contract = ${JSON.stringify(generated, null, 2)} as const\n\nexport type LetterpressContract = typeof contract\n`,
)

function sortObject(value) {
  return Object.fromEntries(
    Object.entries(value).sort(([left], [right]) => left.localeCompare(right)),
  )
}
